package Jobsheet15;

public class Custumer {
    public int id;
    public String name;

    public Custumer() {
    }

    public Custumer(int id, String name) {
        this.id = id;
        this.name = name;
    }

    public String toString() {
        return "ID: " + id + ", Nama: " + name;
    }

    
}
